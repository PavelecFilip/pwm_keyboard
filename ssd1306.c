// ─────────────────────────────────────────────────────────────────────────────
// Framebuffer v RAM
// ─────────────────────────────────────────────────────────────────────────────
static uint8_t fb[SSD1306_BUFFER_SIZE];

// ─────────────────────────────────────────────────────────────────────────────
// Interní pomocné funkce
// ─────────────────────────────────────────────────────────────────────────────
static void ssd1306_send_cmd(i2c_inst_t *i2c, uint8_t cmd) {
    uint8_t buf[2] = {0x00, cmd}; // 0x00 = Co=0, D/C#=0 → příkaz
    i2c_write_blocking(i2c, SSD1306_I2C_ADDR, buf, 2, false);
}

static void ssd1306_send_data(i2c_inst_t *i2c, uint8_t *data, size_t len) {
    // Statický buffer — vyhne se alokaci 513 B na stacku při každém volání
    static uint8_t buf[SSD1306_BUFFER_SIZE + 1];
    buf[0] = 0x40;  // D/C#=1 → data
    memcpy(buf + 1, data, len);
    i2c_write_blocking(i2c, SSD1306_I2C_ADDR, buf, len + 1, false);
}

// ─────────────────────────────────────────────────────────────────────────────
// Veřejné funkce
// ─────────────────────────────────────────────────────────────────────────────
void ssd1306_init(i2c_inst_t *i2c) {
    // Krátká pauza pro jistotu – displej potřebuje čas po přivedení napájení
    sleep_ms(50);

    // Inicializační sekvence pro SSD1306 128x32
    ssd1306_send_cmd(i2c, SSD1306_DISPLAY_OFF);
    ssd1306_send_cmd(i2c, SSD1306_SET_DISPLAY_CLOCK);   ssd1306_send_cmd(i2c, 0x80);
    ssd1306_send_cmd(i2c, SSD1306_SET_MULTIPLEX);       ssd1306_send_cmd(i2c, 0x1F); // 32-1
    ssd1306_send_cmd(i2c, SSD1306_SET_DISPLAY_OFFSET);  ssd1306_send_cmd(i2c, 0x00);
    ssd1306_send_cmd(i2c, SSD1306_SET_START_LINE | 0x0);
    ssd1306_send_cmd(i2c, SSD1306_CHARGE_PUMP);         ssd1306_send_cmd(i2c, 0x14);
    ssd1306_send_cmd(i2c, SSD1306_MEMORY_MODE);         ssd1306_send_cmd(i2c, 0x00); // horizontal
    ssd1306_send_cmd(i2c, SSD1306_SEG_REMAP);
    ssd1306_send_cmd(i2c, SSD1306_COM_SCAN_DEC);
    ssd1306_send_cmd(i2c, SSD1306_SET_COM_PINS);        ssd1306_send_cmd(i2c, 0x02); // 32px výška
    ssd1306_send_cmd(i2c, SSD1306_SET_CONTRAST);        ssd1306_send_cmd(i2c, 0x8F);
    ssd1306_send_cmd(i2c, SSD1306_SET_PRECHARGE);       ssd1306_send_cmd(i2c, 0xF1);
    ssd1306_send_cmd(i2c, SSD1306_SET_VCOM_DETECT);     ssd1306_send_cmd(i2c, 0x40);
    ssd1306_send_cmd(i2c, SSD1306_DISPLAY_ALL_ON_RESUME);
    ssd1306_send_cmd(i2c, SSD1306_NORMAL_DISPLAY);
    ssd1306_send_cmd(i2c, SSD1306_DISPLAY_ON);

    ssd1306_clear();
    ssd1306_show(i2c);
}

void ssd1306_clear(void) {
    memset(fb, 0, SSD1306_BUFFER_SIZE);
}

void ssd1306_show(i2c_inst_t *i2c) {
    // Nastav rozsah sloupců a stránek
    ssd1306_send_cmd(i2c, SSD1306_COLUMN_ADDR);
    ssd1306_send_cmd(i2c, 0);
    ssd1306_send_cmd(i2c, SSD1306_WIDTH - 1);
    ssd1306_send_cmd(i2c, SSD1306_PAGE_ADDR);
    ssd1306_send_cmd(i2c, 0);
    ssd1306_send_cmd(i2c, (SSD1306_HEIGHT / 8) - 1); // 3 pro 32px

    ssd1306_send_data(i2c, fb, SSD1306_BUFFER_SIZE);
}

void ssd1306_draw_pixel(int x, int y, bool on) {
    if (x < 0 || x >= SSD1306_WIDTH || y < 0 || y >= SSD1306_HEIGHT) return;
    int byte_idx = x + (y / 8) * SSD1306_WIDTH;
    uint8_t bit = 1 << (y % 8);
    if (on) {
        fb[byte_idx] |= bit;
    } else {
        fb[byte_idx] &= ~bit;
    }
}

void ssd1306_draw_string(int x, int y, const char *str) {
    while (*str) {
        char c = *str++;
        if (c < 32 || c > 126) c = '?';
        const uint8_t *glyph = font5x7[c - 32];
        for (int col = 0; col < 5; col++) {
            uint8_t line = glyph[col];
            for (int row = 0; row < 7; row++) {
                ssd1306_draw_pixel(x + col, y + row, (line >> row) & 1);
            }
        }
        x += 6; // 5px znak + 1px mezera
        if (x + 5 >= SSD1306_WIDTH) break;
    }
}

void ssd1306_draw_rect(int x, int y, int w, int h, bool on) {
    for (int i = x; i < x + w; i++) {
        ssd1306_draw_pixel(i, y,         on);
        ssd1306_draw_pixel(i, y + h - 1, on);
    }
    for (int j = y; j < y + h; j++) {
        ssd1306_draw_pixel(x,         j, on);
        ssd1306_draw_pixel(x + w - 1, j, on);
    }
}

void ssd1306_fill_rect(int x, int y, int w, int h, bool on) {
    for (int j = y; j < y + h; j++) {
        for (int i = x; i < x + w; i++) {
            ssd1306_draw_pixel(i, j, on);
        }
    }
}
